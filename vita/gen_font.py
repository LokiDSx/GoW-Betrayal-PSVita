#!/usr/bin/env python3
"""Render the fixed ASCII font the Vita error screen draws with.

Output is a C include so the runtime needs no font file and no FreeType:
    python vita/gen_font.py <dejavu.ttf> <font8x8.inc>
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CELL_W, CELL_H = 16, 20
FIRST, LAST = 32, 126
SIZE = 16
THRESHOLD = 112


def main(ttf: Path, out: Path) -> None:
    font = ImageFont.truetype(str(ttf), SIZE)
    ascent, _ = font.getmetrics()
    baseline = min(ascent, CELL_H - 1)

    glyphs, advances = [], []
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (CELL_W, CELL_H), 0)
        ImageDraw.Draw(img).text((0, baseline), chr(code), font=font, fill=255, anchor="ls")
        px = img.load()
        rows = []
        for y in range(CELL_H):
            bits = 0
            for x in range(CELL_W):
                if px[x, y] >= THRESHOLD:
                    bits |= 0x8000 >> x
            rows.append(bits)
        glyphs.append("  {" + ", ".join(f"0x{b:04x}" for b in rows) + "}")
        advances.append(max(1, round(font.getlength(chr(code)))))

    out.write_text(
        "// Generated by vita/gen_font.py from "
        + ttf.name
        + f" at {SIZE}px. Do not edit by hand.\n"
        f"// ASCII {FIRST}..{LAST}, {CELL_H} rows of {CELL_W} bits, MSB = leftmost pixel.\n"
        "static const unsigned short kFontGlyph[95][20] = {\n"
        + ",\n".join(glyphs)
        + "\n};\n"
        "static const unsigned char kFontAdvance[95] = {"
        + ", ".join(str(a) for a in advances)
        + "};\n"
        f"static const int kFontHeight = {CELL_H};\n",
        encoding="utf-8",
    )
    print(f"{out}: {LAST - FIRST + 1} glyphs, height {CELL_H}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
